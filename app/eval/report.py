"""docs/EVAL.md: every number comes from var/eval/*.json; conclusions are computed, not written by hand."""

from __future__ import annotations

import json
from pathlib import Path

from sqlmodel import Session, func, select

from app import clock
from app.config import REPO_ROOT, RULES, get_settings, rules_hash
from app.embeddings import embedding_status
from app.eval.svg import line_chart
from app.models import Candidate, InteractionEvent, Job

EVAL_MD = REPO_ROOT / "docs" / "EVAL.md"
EVAL_DIR = REPO_ROOT / "docs" / "eval"


def results_dir() -> Path:
    d = get_settings().eval_dir
    d.mkdir(parents=True, exist_ok=True)
    return d


def save_result(name: str, data: dict) -> Path:
    p = results_dir() / f"{name}.json"
    p.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    return p


def load_result(name: str) -> dict | None:
    p = results_dir() / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def _f(x: object, digits: int = 3) -> str:
    return "—" if x is None else (f"{x:.{digits}f}" if isinstance(x, float) else str(x))


def _count(session: Session, model, *where) -> int:  # type: ignore[no-untyped-def]
    q = select(func.count()).select_from(model)
    for w in where:
        q = q.where(w)
    return int(session.exec(q).one())


def write_report(session: Session, out_md: Path = EVAL_MD) -> Path:
    charts = out_md.parent / "eval"
    replay, drift = load_result("replay"), load_result("drift")
    congestion, latency = load_result("congestion"), load_result("latency")
    lines = [
        "# Evaluation",
        "",
        "> Generated by `encaixe eval report` from `var/eval/*.json`. Numbers are reported as they came out, "
        "including when learning from swipes does **not** beat the static ranking.",
        "",
        f"- Generated: {clock.now().strftime('%Y-%m-%d %H:%M UTC')} · rules `{rules_hash()}` · "
        f"embeddings `{embedding_status().get('active') or get_settings().embeddings}`",
        f"- Data: {_count(session, Job, Job.status == 'open')} open jobs, "
        f"{_count(session, Candidate, Candidate.synthetic == True)} synthetic and "  # noqa: E712
        f"{_count(session, Candidate, Candidate.synthetic == False)} real candidates, "  # noqa: E712
        f"{_count(session, InteractionEvent)} events.",
        f"- Served ranker: `{RULES.rankers.default}`; default aggregator: `{RULES.aggregation.aggregator}`.",
        "",
    ]
    if replay:
        rows = replay["variants"]
        lines += [
            "## 1. Replay of the recorded history",
            "",
            f"{replay['sessions']} candidate sessions, {replay['events']} judgments. For each session the "
            "ranking is rebuilt with what was known before it; the table shows where the liked jobs landed.",
            "",
            "| Variant | liked items | MRR | Recall@5 | Recall@10 | Recall@20 | NDCG@10 | AUC (likes vs dislikes) |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for name, m in rows.items():
            lines.append(
                f"| {name} | {m['liked_items']} | {_f(m['mrr'])} | {_f(m['recall@5'])} | {_f(m['recall@10'])} "
                f"| {_f(m['recall@20'])} | {_f(m['ndcg@10'])} | {_f(m['auc'])} |"
            )
        st, fbk = rows.get("static-v1 (rank_sum)"), rows.get("feedback-v1")
        if st and fbk:
            d_mrr, d_auc = fbk["mrr"] - st["mrr"], (fbk["auc"] or 0) - (st["auc"] or 0)
            verdict = "beats" if d_mrr > 0.005 and d_auc >= 0 else ("does not beat" if d_mrr < -0.005 else "ties with")
            lines += [
                "",
                f"**Reading:** `feedback-v1` {verdict} `static-v1` on this history "
                f"(MRR {_f(fbk['mrr'])} vs {_f(st['mrr'])}, AUC {_f(fbk['auc'])} vs {_f(st['auc'])}).",
            ]
        aggs = {k: v for k, v in rows.items() if k.startswith("static-v1")}
        if aggs:
            best = max(aggs, key=lambda k: aggs[k]["mrr"])
            lines.append(
                f"Among the aggregators, the best MRR is `{best}`. The default (`rank_sum`) only changes if "
                "the numbers say so on real histories; with a synthetic history this is a sanity check, not a "
                "decision."
            )
        lines += [
            "",
            f"Limitations: {replay.get('note')}. The history was produced by simulated people swiping on "
            "decks served by `feedback-v1`, so the replay inherits that logging policy.",
            "",
        ]
    if drift:
        charts.mkdir(parents=True, exist_ok=True)
        curves = drift["curves"]
        line_chart(
            {k: v["precision@10"] for k, v in curves.items()},
            charts / "drift_precision_all.svg",
            "Drift: precision@10 (all simulated users)",
            "precision@10",
            drift["drift_day"],
            "mudança",
        )
        line_chart(
            {k: v["precision@10 (quem mudou)"] for k, v in curves.items()},
            charts / "drift_precision_drifters.svg",
            "Drift: precision@10 (users whose preference changed)",
            "precision@10",
            drift["drift_day"],
            "mudança",
        )
        lines += [
            "## 2. Drift: the preference changes on a known day",
            "",
            f"{drift['users']} simulated users over {drift['days']} days on {drift['jobs']} open jobs. On day "
            f"{drift['drift_day']}, {drift['drifters']} users change their preferred area; "
            f"{drift['drifters_with_revision']} of them also save a relevant revision (a new dated experience in "
            "the new area), the others change taste only. Quality is measured on the full top 10 against the "
            "current oracle (the simulation's hidden utility).",
            "",
            "![precision all](eval/drift_precision_all.svg)",
            "",
            "![precision drifters](eval/drift_precision_drifters.svg)",
            "",
            "Precision@10 of the users whose preference changed:",
            "",
            "| Variant | 7 days before | 3 days right after | last 5 days | days to recover 90% |",
            "|---|---|---|---|---|",
        ]
        d0, horizon = drift["drift_day"], drift["days"] - drift["drift_day"]

        def avg(xs: list[float]) -> float | None:
            return sum(xs) / len(xs) if xs else None

        summary = {}
        for name, v in curves.items():
            c = v["precision@10 (quem mudou)"]
            row = (avg(c[max(0, d0 - 7) : d0]), avg(c[d0 : d0 + 3]), avg(c[-5:]))
            summary[name] = row
            rec = v["recovery_days"]
            rec_text = str(rec) if rec is not None else f"not within {horizon} days"
            lines.append(f"| {name} | {_f(row[0])} | {_f(row[1])} | {_f(row[2])} | {rec_text} |")
        st, fbk = summary.get("static-v1"), summary.get("feedback-v1")
        if st and fbk and None not in st + fbk:
            lines += [
                "",
                "**Reading:** before the change, learning from swipes "
                f"{'helps' if fbk[0] > st[0] + 0.005 else 'does not help'} "
                f"({_f(fbk[0])} vs {_f(st[0])}). Right after it, `feedback-v1` "
                f"{'falls further than' if fbk[1] < st[1] else 'falls less than'} the static ranking "
                f"({_f(fbk[1])} vs {_f(st[1])}): old likes point the wrong way. At the end of the window it is "
                f"{'above' if fbk[2] > st[2] + 0.005 else 'not above'} static ({_f(fbk[2])} vs {_f(st[2])}).",
            ]
            nd = summary.get("feedback-v1 sem decaimento")
            if nd and nd[2] is not None:
                lines.append(
                    f"Without time decay the end-of-window precision is {_f(nd[2])} "
                    f"({'worse' if nd[2] < fbk[2] - 0.005 else 'not worse'} than with the "
                    f"{RULES.feedback.half_life_days:g}-day half-life)."
                )
        lines += [
            "",
            "Caveat: the oracle is a weighted sum of area affinity, requirements, seniority, salary and "
            "arrangement, so any experiment built on it favours rankings that look like it (see the weighted "
            "baseline in the replay).",
            "",
        ]
    if congestion:
        c = congestion
        lines += [
            "## 3. Congestion (measured, not optimized)",
            "",
            f"Top {c['top']} candidates of each of the {c['platform_jobs']} open platform jobs ({c['slots']} slots, "
            f"pool of {c['eligible_pool']} eligible candidates).",
            "",
            "| distinct candidates in the top lists | expected if random | max lists per candidate | "
            "share of slots of the top 1% | Gini of exposure |",
            "|---|---|---|---|---|",
            f"| {c['distinct_candidates']} | {c['expected_distinct_if_random']} | {c['max_exposure']} | "
            f"{_f(c['share_of_slots_top1pct'])} | {_f(c['gini'])} |",
            "",
            "A Gini close to 1 means the same few people fill every recruiter's top; the MVP reports it so the "
            "trade-off is visible (exploration slots are the only mitigation today).",
            "",
        ]
    if latency and "error" not in latency:
        jc, cj = latency["jobs_for_candidate"], latency["candidates_for_job"]
        lines += [
            "## 4. Latency",
            "",
            "| ranking | n | p50 | p95 | target p95 |",
            "|---|---|---|---|---|",
            f"| jobs for one candidate | {jc['n']} | {jc['p50_ms']:.0f} ms | {jc['p95_ms']:.0f} ms | "
            f"{latency['target_p95_ms']} ms |",
            f"| candidates for one job | {cj['n']} | {cj['p50_ms']:.0f} ms | {cj['p95_ms']:.0f} ms | "
            f"{latency['target_p95_ms']} ms |",
            "",
        ]
    bench = load_result("bench")
    if bench:
        lines += ["## 5. Memory (encaixe bench)", "", "| step | peak RSS | budget |", "|---|---|---|"]
        for step in bench.get("steps", []):
            lines.append(f"| {step['name']} | {step['peak_mb']:.0f} MB | {step['budget_mb']} MB |")
        lines.append("")
    out_md.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return out_md
